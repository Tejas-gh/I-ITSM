-- A4: persistence for the existing Notification record (domain.notification.Notification).
-- seq gives insertion order for findAll / findByRecipientId (new table, so no change to V1/V2 tables).
-- No foreign keys on purpose (same approach as audit_entries): recipient and incident are plain ids.
CREATE TABLE notifications (
    seq             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id VARCHAR(100)  NOT NULL,
    recipient_id    VARCHAR(100)  NOT NULL,
    title           VARCHAR(500)  NOT NULL,
    body            VARCHAR(4000) NOT NULL,
    incident_id     VARCHAR(100)  NOT NULL,
    channel_name    VARCHAR(100)  NOT NULL,
    is_read         BOOLEAN       NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_notifications_notification_id UNIQUE (notification_id)
);
