-- A3: persistence for SLA alerts (domain.sla.SlaAlert), the record of SLA warnings and violations.
-- seq gives insertion order for findAll / findByKind / findByIncidentId.
-- (incident_id, sla_type, kind) is the idempotency key: the same alert can never be stored twice.
-- No foreign keys on purpose (same approach as audit_entries / notifications): incident_id is a plain id.
CREATE TABLE sla_alerts (
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id    VARCHAR(200) NOT NULL,
    incident_id VARCHAR(100) NOT NULL,
    sla_type    VARCHAR(20)  NOT NULL,
    kind        VARCHAR(20)  NOT NULL,
    deadline    TIMESTAMP WITH TIME ZONE NOT NULL,
    raised_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_sla_alerts_alert_id UNIQUE (alert_id),
    CONSTRAINT uq_sla_alerts_key UNIQUE (incident_id, sla_type, kind),
    CONSTRAINT ck_sla_alerts_type CHECK (sla_type IN ('RESPONSE', 'RESOLUTION')),
    CONSTRAINT ck_sla_alerts_kind CHECK (kind IN ('WARNING', 'VIOLATION'))
);
CREATE INDEX idx_sla_alerts_kind ON sla_alerts (kind);
