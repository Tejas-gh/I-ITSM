-- A7: persistence for escalation state (domain.escalation.EscalationRecord), produced by the B6 escalation chain.
-- Without it a restart forgets which levels were already raised and the same incident is escalated again.
-- (incident_id, escalation_level) is the idempotency key: a level is recorded at most once per incident.
-- id gives insertion order. No foreign keys on purpose (same approach as sla_alerts / audit_entries / notifications).
CREATE TABLE escalations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id      VARCHAR(100) NOT NULL,
    escalation_level INTEGER      NOT NULL,
    target_role      VARCHAR(30)  NOT NULL,
    escalated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    reason           VARCHAR(2000) NOT NULL,
    CONSTRAINT uq_escalations_incident_level UNIQUE (incident_id, escalation_level),
    CONSTRAINT ck_escalations_level CHECK (escalation_level BETWEEN 1 AND 3)
);
